// Profile links with their 24×24 SVG icons
import type { Attachment } from 'svelte/attachments';
import { on } from 'svelte/events';

export interface Link {
	label: string;
	href: string;
	icon: string; // SVG markup inside a 0 0 24 24 viewBox
	me?: boolean; // rel="me" profile link
	attach?: Attachment<HTMLAnchorElement>;
}

// The address is built from char codes at click time, so it never shows as a harvestable string in the HTML
const email: Attachment<HTMLAnchorElement> = (a) =>
	on(a, 'click', (e) => {
		e.preventDefault();
		location.href =
			'mailto:' + String.fromCharCode(115, 105, 116, 101, 64, 109, 117, 114, 102, 97, 108, 111, 46, 99, 111, 109);
	});

// Clean link previews: the browser status bar shows the short href on hover,
// and the real URL goes in only when the link is pressed (any click or Enter)
const revealOnPress =
	(url: string): Attachment<HTMLAnchorElement> =>
	(a) => {
		const short = a.href;
		const go = () => (a.href = url);
		const offs = [
			on(a, 'pointerdown', go),
			on(a, 'keydown', (e) => e.key === 'Enter' && go()),
			on(a, 'mouseleave', () => (a.href = short))
		];
		return () => offs.forEach((off) => off());
	};

